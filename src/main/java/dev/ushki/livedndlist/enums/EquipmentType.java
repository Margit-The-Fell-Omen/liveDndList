package dev.ushki.livedndlist.enums;

/**
 * Enumeration of equipment item types in D&D 5th Edition. Categorizes different kinds of items a
 * character can possess.
 *
 * <p>Equipment types determine:
 * <ul>
 *   <li>How the item can be used</li>
 *   <li>Where it's equipped (if applicable)</li>
 *   <li>What proficiencies are required</li>
 *   <li>How it affects character statistics</li>
 * </ul>
 */
public enum EquipmentType {
  WEAPON, ARMOR, SHIELD, AMMUNITION, GEAR,
  TOOL, MAGIC_ITEM, CONSUMABLE, TREASURE
}
