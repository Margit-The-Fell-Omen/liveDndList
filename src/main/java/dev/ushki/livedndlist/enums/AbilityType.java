package dev.ushki.livedndlist.enums;

/**
 * Enumeration of the six core ability scores in D&D 5th Edition. Each ability represents a
 * different aspect of a character's capabilities.
 *
 * <p>Usage:
 * <ul>
 *   <li>Character ability scores</li>
 *   <li>Skill checks (each skill is tied to one ability)</li>
 *   <li>Saving throws</li>
 *   <li>Spellcasting ability for different classes</li>
 * </ul>
 */
public enum AbilityType {
  STRENGTH, DEXTERITY, CONSTITUTION,
  INTELLIGENCE, WISDOM, CHARISMA
}
