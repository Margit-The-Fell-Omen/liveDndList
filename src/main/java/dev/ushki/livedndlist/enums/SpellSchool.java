package dev.ushki.livedndlist.enums;

/**
 * Enumeration of the eight schools of magic in D&D 5th Edition. Each school represents a different
 * type of magical effect and study.
 *
 * <p>Wizard subclasses often specialize in one school, gaining enhanced
 * abilities when casting spells of that school and unique features.
 *
 * <p>The schools categorize all spells except cantrips and those with
 * unique classifications in certain settings.
 */
public enum SpellSchool {
  ABJURATION, CONJURATION, DIVINATION, ENCHANTMENT,
  EVOCATION, ILLUSION, NECROMANCY, TRANSMUTATION
}
